/*
 * ITACHI HAL for POCO X6 Pro (duchamp, MT6897) running ColorOS/OxygenOS 16.
 * Written from scratch for this project. Author: Itachi.
 *
 * Provides the two vendor AIDL HALs that ColorOS system_server talks to:
 *   vendor.oplus.hardware.touch.IOplusTouch/default                        (v2)
 *   vendor.oplus.hardware.displaypanelfeature.IDisplayPanelFeature/default (v1)
 * and maps them onto Xiaomi/MTK kernel nodes:
 *   DT2W   -> touch_dev node (auto-discovered or set in itachi.conf)
 *   AOD    -> /sys/class/mi_display/disp-DSI-0/doze_brightness
 *   FOD    -> pass-through (mfp-daemon owns LHBM); every call is traced
 *
 * Wire format (transaction codes, parcel layout) was derived from the AIDL
 * stubs inside the ROM's own services.jar, so it matches ColorOS exactly.
 * Only the public libbinder_ndk C API is used (no generated code needed).
 */
