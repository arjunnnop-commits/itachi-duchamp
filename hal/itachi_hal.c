#define TAG "itachi-hal"
#define CONF_PATH "/vendor/etc/itachi/itachi.conf"


/* meta transactions generated by AIDL for every interface */
#define TXN_IFACE_VERSION 16777215u
#define TXN_IFACE_HASH    16777214u

/* ColorOS constants, read from the ROM (OplusTouchNodeManager / OplusDisplayPanelFeatureHelper) */
#define NODE_DOUBLE_TAP_ENABLE 1
#define OMMDP_AOD              7
#define OMMDP_MAX_BRIGHTNESS   8
#define OMMDP_FPPRESS          28
#define OMMDP_UDFPS_TYPE       211  /* verified in SystemUI: getUdfpsType() reads 0xd3; bit 0x10 and bit 0x400 gate local-HBM logic */
#define OMMDP_AOD_SMOOTH       217  /* verified: SmoothTransitionController reads 0xd9 (int[]) */
#define OMMDP_DIMLAY_HBM       22   /* verified: OMMDP_DIMLAY_HBM = 0x16 in OOS16 services */
#define OMMDP_NORMAL_MAXBRIGHT 247
#define NOTIFY_DISP_FINGER_LAYER 20004
#define FEATURE_SLOTS 512

static struct {
    int  trace;
    char doze_node[160];
    char maxbr_node[160];
    char panel_info_node[160];
    char dt2w_node[160];
    int  aod_map[8];         /* ColorOS AOD value -> doze_brightness */
    int  default_maxbr;
} cfg = {
    .trace = 1,
    .doze_node = "/sys/class/mi_display/disp-DSI-0/doze_brightness",
    .maxbr_node = "/sys/class/mi_display/disp-DSI-0/factory_max_brightness",
    .panel_info_node = "/sys/class/mi_display/disp-DSI-0/panel_info",
    .dt2w_node = "",
    .aod_map = {0, 1, 2, 2, 2, 2, 2, 2},
    .default_maxbr = 2047,
};

static int g_feature[FEATURE_SLOTS];
static char g_dt2w_state[16] = "0";
static pthread_mutex_t g_lock = PTHREAD_MUTEX_INITIALIZER;

static void LOG(const char *fmt, ...) {
    va_list ap; va_start(ap, fmt);
    __android_log_vprint(ANDROID_LOG_INFO, TAG, fmt, ap);
    va_end(ap);
}
#define TRACE(...) do { if (cfg.trace) LOG(__VA_ARGS__); } while (0)
void itachi_trace(const char *fmt, ...) {
    if (!cfg.trace) return;
    va_list ap; va_start(ap, fmt);
    __android_log_vprint(ANDROID_LOG_INFO, TAG, fmt, ap);
    va_end(ap);
}
static int g_saved_doze = 0;

/* ---------- small file helpers ---------- */
static int write_node(const char *path, const char *val) {
    int fd = open(path, O_WRONLY | O_CLOEXEC);
    if (fd < 0) { LOG("write %s='%s' open failed: %s", path, val, strerror(errno)); return -errno; }
    ssize_t n = write(fd, val, strlen(val));
    int e = errno;
    close(fd);
    if (n < 0) { LOG("write %s='%s' failed: %s", path, val, strerror(e)); return -e; }
    TRACE("write %s='%s' ok", path, val);
    return 0;
}
static int read_node(const char *path, char *buf, size_t sz) {
    int fd = open(path, O_RDONLY | O_CLOEXEC);
    if (fd < 0) return -errno;
    ssize_t n = read(fd, buf, sz - 1);
    close(fd);
    if (n < 0) return -errno;
    buf[n] = 0;
    while (n > 0 && (buf[n-1] == '\n' || buf[n-1] == '\r' || buf[n-1] == ' ')) buf[--n] = 0;
    return (int)n;
}

static void load_conf(void) {
    FILE *f = fopen(CONF_PATH, "re");
    if (!f) { LOG("no %s, using defaults", CONF_PATH); return; }
    char line[256];
    while (fgets(line, sizeof line, f)) {
        char *eq = strchr(line, '=');
        if (!eq || line[0] == '#') continue;
        *eq = 0; char *k = line, *v = eq + 1;
        v[strcspn(v, "\r\n")] = 0;
        if (!strcmp(k, "trace")) cfg.trace = atoi(v);
        else if (!strcmp(k, "doze_node")) snprintf(cfg.doze_node, sizeof cfg.doze_node, "%s", v);
        else if (!strcmp(k, "maxbr_node")) snprintf(cfg.maxbr_node, sizeof cfg.maxbr_node, "%s", v);
        else if (!strcmp(k, "panel_info_node")) snprintf(cfg.panel_info_node, sizeof cfg.panel_info_node, "%s", v);
        else if (!strcmp(k, "dt2w_node")) snprintf(cfg.dt2w_node, sizeof cfg.dt2w_node, "%s", v);
        else if (!strcmp(k, "default_maxbr")) cfg.default_maxbr = atoi(v);
        else if (!strcmp(k, "aod_map")) {            /* e.g. aod_map=0,1,2,2 */
            int i = 0; for (char *t = strtok(v, ","); t && i < 8; t = strtok(NULL, ",")) cfg.aod_map[i++] = atoi(t);
        }
    }
    fclose(f);
}

/* Find the double-tap node under touch_dev the first time it is needed. */
static const char *dt2w_path(void) {
    static char found[200];
    if (cfg.dt2w_node[0]) return cfg.dt2w_node;
    if (found[0]) return found;
    static const char *pats[] = {"double", "dt2w", "dbtap", "doubletap", NULL};
    DIR *d = opendir("/sys/class/touch/touch_dev/");
    if (!d) { LOG("cannot open touch_dev: %s", strerror(errno)); return NULL; }
    struct dirent *e;
    while ((e = readdir(d))) {
        for (int i = 0; pats[i]; i++)
            if (strcasestr(e->d_name, pats[i])) {
                snprintf(found, sizeof found, "/sys/class/touch/touch_dev/%s", e->d_name);
                LOG("DT2W node auto-detected: %s", found);
                closedir(d); return found;
            }
    }
    closedir(d);
    LOG("DT2W node NOT found under touch_dev; set dt2w_node= in itachi.conf");
    return NULL;
}

/* ---------- parcel helpers (public libbinder_ndk API only) ---------- */
static bool str_alloc(void *data, int32_t len, char **buf) {
    char **out = (char **)data;
    if (len < 0) { *out = NULL; *buf = NULL; return true; }
    *out = malloc((size_t)len + 1);
    if (!*out) return false;
    (*out)[len] = 0;
    *buf = *out;
    return true;
}
struct i32arr { int32_t *p; int32_t n; };
static bool i32_alloc(void *data, int32_t len, int32_t **buf) {
    struct i32arr *a = data;
    a->n = len < 0 ? 0 : len;
    a->p = calloc((size_t)(a->n ? a->n : 1), sizeof(int32_t));
    if (!a->p) return false;
    *buf = a->p;
    return true;
}
static void ok_header(AParcel *out) {
    AStatus *st = AStatus_newOk();
    AParcel_writeStatusHeader(out, st);
    AStatus_delete(st);
}
static bool str_get(const void *arr, size_t i, const char **s, int32_t *len) {
    const char *const *a = arr; *s = a[i]; *len = (int32_t)strlen(a[i]); return true;
}

/* ---------- DisplayPanelFeature ---------- */
int itachi_write_doze(int v) { char s[16]; snprintf(s, sizeof s, "%d", v); return write_node(cfg.doze_node, s); }
int itachi_saved_doze(void) { return g_saved_doze; }
static int dpf_get(int feature) {
    int v;
    char buf[64];
    switch (feature) {
    case OMMDP_UDFPS_TYPE:
        v = itachi_udfps_type();      /* tells SystemUI the panel has local HBM: no dim layer / black box */
        break;
    case OMMDP_MAX_BRIGHTNESS:
    case OMMDP_NORMAL_MAXBRIGHT:
        v = (read_node(cfg.maxbr_node, buf, sizeof buf) > 0) ? atoi(buf) : cfg.default_maxbr;
        break;
    default:
        v = (feature >= 0 && feature < FEATURE_SLOTS) ? g_feature[feature] : 0;
    }
    TRACE("DPF get(%d) -> %d", feature, v);
    return v;
}

static int dpf_set(int feature, const int32_t *v, int n) {
    TRACE("DPF set(%d) n=%d v0=%d v1=%d", feature, n, n > 0 ? v[0] : -1, n > 1 ? v[1] : -1);
    int a0 = n > 0 ? v[0] : 0;
    if (feature >= 0 && feature < FEATURE_SLOTS) g_feature[feature] = a0;
    switch (feature) {
    case OMMDP_AOD: {
        int idx = a0 < 0 ? 0 : (a0 > 7 ? 7 : a0);
        g_saved_doze = cfg.aod_map[idx];
        itachi_fod_aod_changed();
        itachi_write_doze(g_saved_doze);   /* failure is logged, never returned: ColorOS must not see an error */
        break;
    }
    case OMMDP_AOD_SMOOTH:
        break;                              /* accepted, stored in g_feature, always success */
    case OMMDP_DIMLAY_HBM:
        if (a0 == 0) itachi_fod_hbm_off();  /* HBM off -> disarm FOD touch immediately */
        break;
    case OMMDP_FPPRESS:
    case NOTIFY_DISP_FINGER_LAYER:
        itachi_fod_layer(a0);               /* mfp-daemon still owns LHBM; we gate the touch IC */
        break;
    default: break;
    }
    return 0;
}

static binder_status_t dpf_txn(AIBinder *b, transaction_code_t code, const AParcel *in, AParcel *out) {
    (void)b;
    switch (code) {
    case 1: { /* int getDisplayPanelFeatureValue(int feature, out int[] value) */
        int32_t feature = 0, len = 0;
        AParcel_readInt32(in, &feature);
        AParcel_readInt32(in, &len);
        if (len < 0) len = 0;
        int32_t *arr = calloc((size_t)(len ? len : 1), sizeof(int32_t));
        if (len > 0) arr[0] = dpf_get(feature);
        ok_header(out);
        AParcel_writeInt32(out, 0);
        AParcel_writeInt32Array(out, arr, len);
        free(arr);
        return STATUS_OK;
    }
    case 2: { /* int setDisplayPanelFeatureValue(int feature, in int[] value) */
        int32_t feature = 0;
        struct i32arr a = {0};
        AParcel_readInt32(in, &feature);
        AParcel_readInt32Array(in, &a, i32_alloc);
        int r = dpf_set(feature, a.p, a.n);
        free(a.p);
        ok_header(out);
        AParcel_writeInt32(out, r);
        return STATUS_OK;
    }
    case 3: { /* int getDisplayPanelInfo(int id, out List<String> info) */
        int32_t id = 0; char buf[256] = "unknown";
        AParcel_readInt32(in, &id);
        if (read_node(cfg.panel_info_node, buf, sizeof buf) <= 0) snprintf(buf, sizeof buf, "duchamp");
        TRACE("DPF info(%d) -> %s", id, buf);
        const char *items[1] = {buf};
        ok_header(out);
        AParcel_writeInt32(out, 0);
        AParcel_writeStringArray(out, items, 1, str_get);
        return STATUS_OK;
    }
    case TXN_IFACE_VERSION: ok_header(out); AParcel_writeInt32(out, 1); return STATUS_OK;
    case TXN_IFACE_HASH:    ok_header(out); AParcel_writeString(out, itachi_sealed(S_DPF_HASH), -1); return STATUS_OK;
    default: LOG("DPF unknown txn %u", code); return STATUS_UNKNOWN_TRANSACTION;
    }
}

/* ---------- IOplusTouch ---------- */
static int touch_write(int node, int dev, const char *val) {
    TRACE("touch write node=%d dev=%d val='%s'", node, dev, val ? val : "(null)");
    if (node != NODE_DOUBLE_TAP_ENABLE || !val) return 0;     /* other nodes: accept, ignore */
    pthread_mutex_lock(&g_lock);
    snprintf(g_dt2w_state, sizeof g_dt2w_state, "%s", val);
    pthread_mutex_unlock(&g_lock);
    const char *p = dt2w_path();
    if (!p) return 0;
    write_node(p, val);
    return 0;
}

static binder_status_t touch_txn(AIBinder *b, transaction_code_t code, const AParcel *in, AParcel *out) {
    (void)b;
    switch (code) {
    case 1: /* int initialize() */
        ok_header(out); AParcel_writeInt32(out, 0); return STATUS_OK;
    case 2: { /* int isTouchNodeSupport(int node, int dev) */
        int32_t node = 0, dev = 0;
        AParcel_readInt32(in, &node); AParcel_readInt32(in, &dev);
        int s = (node == NODE_DOUBLE_TAP_ENABLE && dt2w_path() != NULL) ? 1 : 0;
        TRACE("touch isNodeSupport(%d,%d) -> %d", node, dev, s);
        ok_header(out); AParcel_writeInt32(out, s); return STATUS_OK;
    }
    case 3: { /* String touchReadNodeFile(int node, int dev) */
        int32_t node = 0, dev = 0; char tmp[16];
        AParcel_readInt32(in, &node); AParcel_readInt32(in, &dev);
        pthread_mutex_lock(&g_lock);
        snprintf(tmp, sizeof tmp, "%s", node == NODE_DOUBLE_TAP_ENABLE ? g_dt2w_state : "0");
        pthread_mutex_unlock(&g_lock);
        TRACE("touch read(%d,%d) -> %s", node, dev, tmp);
        ok_header(out); AParcel_writeString(out, tmp, -1); return STATUS_OK;
    }
    case 4: /* int touchWriteNodeFile(int node, int dev, String val) */
    case 5: /* int touchWriteBtInfo(int node, int dev, String val) */
    case 6: { /* oneway void touchWriteNodeFileOneWay(int node, int dev, String val) */
        int32_t node = 0, dev = 0; char *val = NULL;
        AParcel_readInt32(in, &node); AParcel_readInt32(in, &dev);
        AParcel_readString(in, &val, str_alloc);
        int r = (code == 5) ? 0 : touch_write(node, dev, val);
        free(val);
        if (code == 6) return STATUS_OK;
        ok_header(out); AParcel_writeInt32(out, r); return STATUS_OK;
    }
    case 7: { /* int touchNotifyClient(int cmd, in OplusTouchInfo info) */
        int32_t cmd = 0; AParcel_readInt32(in, &cmd);
        TRACE("touch notifyClient cmd=%d", cmd);
        ok_header(out); AParcel_writeInt32(out, 0); return STATUS_OK;
    }
    case 8: /* int registerEventCallback(IOplusTouchEventCallback cb) */
    case 9: /* int unregisterEventCallback(IOplusTouchEventCallback cb) */
        ok_header(out); AParcel_writeInt32(out, 0); return STATUS_OK;
    case TXN_IFACE_VERSION: ok_header(out); AParcel_writeInt32(out, 2); return STATUS_OK;
    case TXN_IFACE_HASH:    ok_header(out); AParcel_writeString(out, itachi_sealed(S_TOUCH_HASH), -1); return STATUS_OK;
    default: LOG("touch unknown txn %u", code); return STATUS_UNKNOWN_TRANSACTION;
    }
}

/* ---------- service plumbing ---------- */
static void *on_create(void *a) { return a; }
static void on_destroy(void *u) { (void)u; }

static int publish(const char *desc, AIBinder_Class_onTransact txn, const char *instance) {
    AIBinder_Class *cls = AIBinder_Class_define(desc, on_create, on_destroy, txn);
    if (!cls) { LOG("class define failed: %s", desc); return -1; }
    AIBinder *b = AIBinder_new(cls, NULL);
    if (!b) { LOG("AIBinder_new failed: %s", desc); return -1; }
    /* system_server (system partition) calls us, so the binder must be VINTF-stable. */
    void (*mark)(AIBinder *) = (void (*)(AIBinder *))dlsym(RTLD_DEFAULT, "AIBinder_markVintfStability");
    if (mark) mark(b); else LOG("AIBinder_markVintfStability missing!");
    binder_exception_t ex = AServiceManager_addService(b, instance);
    LOG("addService %s -> %d", instance, (int)ex);
    return ex == EX_NONE ? 0 : -1;
}

int main(void) {
    char why[96];
    int lr = itachi_license_check(why, sizeof why);
    if (lr != 0) {
        LOG("NOT AUTHORIZED (%d): %s. See INSTALLATION.md. HALs not started.", lr, why);
        for (;;) pause();           /* idle, no respawn loop */
    }
    LOG("%s", why);
    load_conf();
    itachi_fod_init(CONF_PATH);
    LOG("starting (trace=%d, doze=%s)", cfg.trace, cfg.doze_node);
    ABinderProcess_setThreadPoolMaxThreadCount(3);
    ABinderProcess_startThreadPool();
    int bad = 0;
    char inst[160];
    snprintf(inst, sizeof inst, "%s/default", itachi_sealed(S_TOUCH_DESC));
    bad |= publish(itachi_sealed(S_TOUCH_DESC), touch_txn, inst);
    snprintf(inst, sizeof inst, "%s/default", itachi_sealed(S_DPF_DESC));
    bad |= publish(itachi_sealed(S_DPF_DESC), dpf_txn, inst);
    if (bad) LOG("one or more services failed to register (check SELinux / vintf manifest)");
    ABinderProcess_joinThreadPool();
    return 1;
}
